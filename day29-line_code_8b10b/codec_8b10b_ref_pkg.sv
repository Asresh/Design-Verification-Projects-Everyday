// ---------------------------------------------------------------------------
// Day29 - codec_8b10b_ref_pkg : the golden reference model
//
// The DUT computes 8b/10b from rules: sub-block tables, a disparity rule, an
// alternating-balanced exception, the D.x.A7 exception, and a re-encode step
// in the receiver.  Any one of those rules can be subtly wrong in a way that
// still round-trips, because the same wrong rule sits on both ends of the
// link.  So this model deliberately contains *no rules at all*:
//
//   * encode is a flat 1024-entry ROM, {rd, k, byte} -> {codeword, rd'},
//     generated by docs/gen_kat.py after that script proved the underlying
//     tables against the five defining properties of the code (DC balance,
//     bounded running disparity, run length <= 5 across all ~143k legal
//     codeword junctions, unique decodability, and comma uniqueness);
//
//   * decode is a flat 2048-entry table, {rd, codeword} -> result, built here
//     at elaboration by brute-force inversion of that ROM.  Every one of the
//     1024 possible 10-bit words is classified in both RD states by asking one
//     question - is this exactly the word the transmitter would have sent? -
//     and never by inspecting sub-blocks.
//
// The only thing the two implementations share is the definition of the code
// itself, which is the point.
//
// Classification, in full:
//     word == enc_rom[rd][s] for some symbol s   -> clean decode of s
//     word == enc_rom[~rd][s] for some symbol s  -> disparity error, still s
//     neither                                    -> code error
//
// Running disparity always follows the bits that actually arrived (see
// rd_advance below), so a corrupted symbol costs a transient RD disagreement
// rather than a permanent one - the property the "single bit error, then
// recovery" corner test exists to demonstrate.
// ---------------------------------------------------------------------------

`timescale 1ns/1ps

package codec_8b10b_ref_pkg;

