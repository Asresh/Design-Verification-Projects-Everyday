  // ---- Known-Answer Table ------------------------------------------------
  int         kat_n = 0;
  string      kat_name [0:63];
  bit [7:0]   kat_data [0:63];
  bit         kat_k    [0:63];
  bit         kat_rd   [0:63];
  bit [9:0]   kat_code [0:63];
  bit         kat_rdo  [0:63];

  function automatic void kat_add(input string name, input bit [7:0] data,
                                  input bit k, input bit rd,
                                  input bit [9:0] code, input bit rd_out);
    kat_name[kat_n] = name;
    kat_data[kat_n] = data;
    kat_k   [kat_n] = k;
    kat_rd  [kat_n] = rd;
    kat_code[kat_n] = code;
    kat_rdo [kat_n] = rd_out;
    kat_n           = kat_n + 1;
  endfunction

  // ---- running disparity implied by a received word ----------------------
  // Stated as a definition rather than borrowed from the DUT: a sub-block with
  // equal ones and zeros leaves RD alone, any other sub-block drives RD to the
  // sign of its own imbalance.  Total, and self-limiting even for words that
  // are not in the code.
  function automatic bit rd_advance(input bit [9:0] cw, input bit rd);
    int n6, n4;
    bit mid;
    n6 = $countones(cw[9:4]);
    n4 = $countones(cw[3:0]);
    mid        = (n6 == 3) ? rd  : ((n6 > 3) ? RD_POS : RD_NEG);
    rd_advance = (n4 == 2) ? mid : ((n4 > 2) ? RD_POS : RD_NEG);
  endfunction

  function automatic bit ref_is_comma(input bit [9:0] cw);
    ref_is_comma = (cw[9:3] == 7'b0011111) || (cw[9:3] == 7'b1100000);
  endfunction

  // ---- build ------------------------------------------------------------
  bit ref_built = 1'b0;

  // Field-by-field rather than an assignment pattern: keeps the package
  // compiling on simulators (Icarus among them) that do not accept named
  // structure literals.
  function automatic ref_rx_t mk_rx(input bit ce, input bit de, input bit k,
                                    input bit [7:0] data, input bit rd_out);
    ref_rx_t r;
    r.code_err = ce;
    r.disp_err = de;
    r.k        = k;
    r.data     = data;
    r.rd_out   = rd_out;
    return r;
  endfunction

