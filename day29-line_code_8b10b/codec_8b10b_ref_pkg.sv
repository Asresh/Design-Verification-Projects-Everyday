  // ---- encode ------------------------------------------------------------
  // kerr mirrors the DUT's specified contract for an unencodable control
  // request: nothing legal goes on the wire (the all-zero word is not a
  // codeword, so the far end reports a code error too) and RD is untouched.
  function automatic ref_tx_t ref_encode(input bit [7:0] data,
                                         input bit       k,
                                         input bit       rd);
    ref_tx_t  t;
    bit [10:0] e;
    ref_build();
    t.kerr = k && !enc_ok[{k, data}];
    if (t.kerr) begin
      t.code   = 10'b0;
      t.rd_out = rd;
    end else begin
      e        = enc_rom[{rd, k, data}];
      t.code   = e[10:1];
      t.rd_out = e[0];
    end
    return t;
  endfunction

  // ---- decode ------------------------------------------------------------
  function automatic ref_rx_t ref_decode(input bit [9:0] cw, input bit rd);
    ref_build();
    ref_decode = dec_tbl[{rd, cw}];
  endfunction

  // ---- one full pass through the link ------------------------------------
  // The caller threads the two running-disparity registers (the transmitter's
  // and the receiver's) so the model holds no hidden state and a scoreboard
  // can replay any stream from any point.
  function automatic ref_exp_t ref_link_step(input bit [7:0] data,
                                             input bit       k,
                                             input bit [9:0] err_mask,
                                             input bit       tx_rd,
                                             input bit       rx_rd);
    bit [9:0] wc;
    ref_tx_t  tx;
    ref_rx_t  rx;
    ref_exp_t e;
    tx = ref_encode(data, k, tx_rd);
    wc = tx.code ^ err_mask;
    rx = ref_decode(wc, rx_rd);
    e.enc_code     = tx.code;
    e.wire_code    = wc;
    e.enc_kerr     = tx.kerr;
    e.enc_comma    = ref_is_comma(tx.code);
    e.enc_rd       = tx.rd_out;
    e.out_data     = rx.data;
    e.out_k        = rx.k;
    e.out_code_err = rx.code_err;
    e.out_disp_err = rx.disp_err;
    e.out_comma    = ref_is_comma(wc);
    e.out_rd       = rx.rd_out;
    return e;
  endfunction

  // ---- what checks the checker -------------------------------------------
  // Replays the committed Known-Answer Table through the model's own encode
  // and decode paths before any DUT result is judged.  Returns the number of
  // mismatches; 0 means the model agrees with the table that docs/gen_kat.py
  // proved.
  function automatic int kat_selfcheck(input bit verbose = 1'b0);
    ref_tx_t  tx;
    ref_rx_t  rx;
    int       bad = 0;
    ref_build();
    for (int i = 0; i < kat_n; i++) begin
      tx = ref_encode(kat_data[i], kat_k[i], kat_rd[i]);
      if (tx.kerr || tx.code !== kat_code[i] || tx.rd_out !== kat_rdo[i]) begin
        bad++;
        $display("  KAT encode MISMATCH %s: got %b rd%0d kerr=%0b, want %b rd%0d",
                 kat_name[i], tx.code, tx.rd_out, tx.kerr, kat_code[i],
                 kat_rdo[i]);
      end
      // and straight back again
      rx = ref_decode(kat_code[i], kat_rd[i]);
      if (rx.code_err || rx.disp_err || rx.data !== kat_data[i] ||
          rx.k !== kat_k[i] || rx.rd_out !== kat_rdo[i]) begin
        bad++;
        $display("  KAT decode MISMATCH %s: got %02h k=%0b ce=%0b de=%0b rd%0d",
                 kat_name[i], rx.data, rx.k, rx.code_err, rx.disp_err,
                 rx.rd_out);
      end
    end
    if (verbose)
      $display("  KAT self-check: %0d vectors, %0d mismatch(es)", kat_n, bad);
    return bad;
  endfunction

  // ---- an independent restatement of the code's defining properties ------
  // Cheap enough to run at the start of every simulation, and it means the
  // committed tables are re-proved inside the simulator rather than only in
  // Python.  Returns the number of violations.
  function automatic int property_selfcheck(input bit verbose = 1'b0);
    int bad = 0, n1, cnt, run, worst = 0;
    bit [9:0] cw;
    bit rd_out;
    ref_build();
    for (int rd = 0; rd < 2; rd++)
      for (int k = 0; k < 2; k++)
        for (int d = 0; d < 256; d++) begin
          if (!enc_ok[{k[0], d[7:0]}]) continue;
          cw     = enc_rom[{rd[0], k[0], d[7:0]}][10:1];
          rd_out = enc_rom[{rd[0], k[0], d[7:0]}][0];
          // P1 - DC balance
          n1 = $countones(cw);
          if (n1 < 4 || n1 > 6) begin
            bad++;
            $display("  P1 VIOLATION: %s%0d.%0d rd%0d -> %b has %0d ones",
                     k[0] ? "K" : "D", d[4:0], d[7:5], rd, cw, n1);
          end
          // P2 - RD' must be what the received bits imply
          if (rd_out !== rd_advance(cw, rd[0])) begin
            bad++;
            $display("  P2 VIOLATION: %s%0d.%0d rd%0d -> %b claims rd%0d",
                     k[0] ? "K" : "D", d[4:0], d[7:5], rd, cw, rd_out);
          end
          // P3 - no run of 6 inside a codeword
          run = 1;
          for (int b = 8; b >= 0; b--) begin
            run = (cw[b] === cw[b+1]) ? run + 1 : 1;
            if (run > worst) worst = run;
          end
          // P5 - the comma belongs to K.28.1/.5/.7 alone
          if (ref_is_comma(cw) && !(k[0] && d[4:0] == 5'd28 &&
              (d[7:5] == 3'd1 || d[7:5] == 3'd5 || d[7:5] == 3'd7))) begin
            bad++;
            $display("  P5 VIOLATION: %s%0d.%0d rd%0d -> %b carries a comma",
                     k[0] ? "K" : "D", d[4:0], d[7:5], rd, cw);
          end
        end
    if (worst > 5) begin
      bad++;
      $display("  P3 VIOLATION: a codeword contains a run of %0d", worst);
    end
    // P4 - unique decodability: every codeword must invert to its own symbol
    cnt = 0;
    for (int rd = 0; rd < 2; rd++)
      for (int k = 0; k < 2; k++)
        for (int d = 0; d < 256; d++) begin
          ref_rx_t rx;
          if (!enc_ok[{k[0], d[7:0]}]) continue;
          cnt++;
          cw = enc_rom[{rd[0], k[0], d[7:0]}][10:1];
          rx = dec_tbl[{rd[0], cw}];
          if (rx.code_err || rx.disp_err || rx.data !== d[7:0] ||
              rx.k !== k[0]) begin
            bad++;
            $display("  P4 VIOLATION: %s%0d.%0d rd%0d -> %b decodes to %02h k=%0b",
                     k[0] ? "K" : "D", d[4:0], d[7:5], rd, cw, rx.data, rx.k);
          end
        end
    if (verbose)
      $display("  property self-check: %0d symbol/RD pairs, longest run %0d, %0d violation(s)",
               cnt, worst, bad);
    return bad;
  endfunction

