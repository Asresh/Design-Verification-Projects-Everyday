  // ---- encode result -----------------------------------------------------
  // Returned as a struct rather than through output arguments: SystemVerilog
  // functions with non-input ports are not portable across simulators.
  typedef struct packed {
    bit [9:0] code;
    bit       rd_out;
    bit       kerr;
  } ref_tx_t;

  // ---- decode result -----------------------------------------------------
  typedef struct packed {
    bit       code_err;
    bit       disp_err;
    bit       k;
    bit [7:0] data;
    bit       rd_out;
  } ref_rx_t;

  // ---- everything the DUT is expected to produce for one request ---------
  typedef struct packed {
