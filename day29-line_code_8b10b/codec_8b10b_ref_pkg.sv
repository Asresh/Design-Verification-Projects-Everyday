    bit [7:0] out_data;
    bit       out_k;
    bit       out_code_err;
    bit       out_disp_err;
    bit       out_comma;
    bit       out_rd;
  } ref_exp_t;

  // Width of ref_exp_t, so a testbench can hold expectations in a plain vector
  // queue (queues of packed structs are not portable).  Assigning a ref_exp_t
  // to and from a vector of this width packs and unpacks it implicitly.
  localparam int REF_EXP_W = 36;

  // ---- the tables --------------------------------------------------------
  bit [10:0] enc_rom [0:1023];   // {rd, k, byte}     -> {code, rd'}
